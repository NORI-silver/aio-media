def load_json(rel, default):
    p = os.path.join(ROOT, rel)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else default


def watch_rows(arts, limit):
    watch = load_json("content/news-watch.json", {})
    triage = load_json("content/news-triage.json", {})
    by_slug = {a["slug"]: a for a in arts if a["cat"] == "news"}
    rows = []
    for it in watch.get("items", [])[:limit]:
        t = triage.get(it["url"], "")
        a = by_slug.get(t.split(":", 1)[1]) if t.startswith("written:") else None
        rel = f' <a class="explain" href="{a["path"]}">解説を読む</a>' if a else ""
        rows.append(f'<li><span class="w-meta"><time datetime="{esc(it["published"][:10])}">{esc(it["published"][:10].replace("-", "."))}</time>'
                    f'<span class="src">{esc(it["source_name"])}</span></span>'
                    f'<a class="w-t" href="{esc(it["url"])}" rel="noopener" target="_blank" lang="en">{esc(it["title"])}</a>{rel}</li>')
    return rows, watch.get("checked", "")[:16].replace("T", " ")


