def crumbs(items):
    """items: [(name, path)]。HTML と BreadcrumbList を返す"""
    allc = [("ホーム", "/")] + items
    h = '<nav class="crumbs" aria-label="パンくず">' + " › ".join(
        f'<a href="{p}">{esc(n)}</a>' if k < len(allc) - 1 else f"<span>{esc(n)}</span>"
        for k, (n, p) in enumerate(allc)) + "</nav>"
    data = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": k + 1, "name": n, "item": BASE + p} for k, (n, p) in enumerate(allc)]}
    return h, data


def card(a):
    return (f'<li class="card"><a href="{a["path"]}"><span class="cat">{esc(CATS[a["cat"]]["name"])}</span>'
            f'<strong>{esc(a["title"])}</strong><span class="desc">{esc(a.get("description", ""))}</span>'
            f'<time datetime="{a.get("updated", "")}">{a.get("updated", "")} 更新</time></a></li>')


# ---------------------------------------------------------------- ページを作る
def write(path, text):
    full = os.path.join(ROOT, path.lstrip("/"), "index.html") if path.endswith("/") else os.path.join(ROOT, path.lstrip("/"))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)
    return full


def clean_generated():
    """前回作ったページを消す(記事を消したり名前を変えたときに古いページが残らないように)"""
    emptied = set()
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if not x.startswith(".") and x not in ("content", "tools", "docs", "assets")]
        for fn in files:
            if fn.endswith(".html"):
                p = os.path.join(d, fn)
                with open(p, encoding="utf-8") as f:
                    if GENERATED_MARK in f.read(400):
                        os.remove(p)
                        emptied.add(d)
    for d in sorted(emptied, key=len, reverse=True):
        while d != ROOT and os.path.isdir(d) and not os.listdir(d):
            os.rmdir(d)
            d = os.path.dirname(d)


def build_article(a, arts):
    cat = CATS[a["cat"]]
    body, toc, faq = markdown(a["body"])
    bc_html, bc_ld = crumbs([(cat["name"], f'/{a["cat"]}/'), (a["title"], a["path"])])
    author = a.get("author", SITE["publisher"])
    article = {"@type": "Article", "headline": a["title"], "description": a.get("description", ""),
               "datePublished": a.get("date"), "dateModified": a.get("updated"),
               "mainEntityOfPage": BASE + a["path"], "inLanguage": "ja",
               "author": {"@type": "Person" if author != SITE["publisher"] else "Organization",
                          "name": author, "url": BASE + "/about/"},
               "publisher": ORG, "image": BASE + "/assets/og.png"}
    lds = [article, bc_ld]
    if faq:
        lds.append({"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": ans}} for q, ans in faq]})
    toc_html = ""
    h2s = [(hid, t, l) for lv, hid, t, l in toc if lv == 2]
    if len(h2s) >= 3:
        toc_html = '<nav class="toc" aria-label="目次"><p>目次</p><ol>' + "".join(
            f'<li><a href="#{hid}">{esc(t)}</a>' + (f' <span class="lv lv-{LEVELS[l][0]}">{l}</span>' if l else "") + "</li>"
            for hid, t, l in h2s) + "</ol></nav>"
    toc_html = level_guide(toc) + toc_html
    summary = f'<p class="summary"><strong>この記事の結論:</strong>{inline(a["summary"])}</p>' if a.get("summary") else ""
    related = [x for x in arts if x["cat"] == a["cat"] and x is not a][:6]
    rel_html = ('<section class="related"><h2>あわせて読みたい</h2><ul class="cards">' + "".join(card(x) for x in related) + "</ul></section>") if related else ""
    page = head(a.get("seo_title", a["title"]), a.get("description", ""), a["path"], lds, "article") + f"""{bc_html}
<article>
<header class="post"><span class="cat"><a href="/{a['cat']}/">{esc(cat['name'])}</a></span>
<h1>{esc(a['title'])}</h1>
<p class="meta">公開 <time datetime="{a.get('date', '')}">{a.get('date', '')}</time> ・ 更新 <time datetime="{a.get('updated', '')}">{a.get('updated', '')}</time> ・ <a href="/about/">{esc(author)}</a></p>
</header>
{summary}
{toc_html}
<div class="body">
{body}
</div>
</article>
{rel_html}
""" + foot()
    write(a["path"], page)


def build_category(c, arts):
    items = [a for a in arts if a["cat"] == c["slug"]]
    path = f'/{c["slug"]}/'
    bc_html, bc_ld = crumbs([(c["name"], path)])
    coll = {"@type": "CollectionPage", "name": c["name"], "description": c["desc"], "url": BASE + path,
            "isPartOf": {"@id": BASE + "/#website"}}
    lst = ('<ul class="cards">' + "".join(card(a) for a in items) + "</ul>") if items else '<p class="empty">記事を準備しています。</p>'
    page = head(f'{c["name"]}の記事一覧|{SITE["name"]}', c["desc"], path, [coll, bc_ld], noindex=not items) + f"""{bc_html}
<h1>{esc(c['name'])}</h1>
<p class="lead">{esc(c['desc'])}</p>
{lst}
""" + foot()
    write(path, page)


