def main():
    clean_generated()
    global ARTS
    arts, pages = load_articles(), load_pages()
    ARTS = arts
    for a in arts:
        for k in ("title", "description", "date"):
            if not a.get(k):
                sys.exit(f"{a['src']}: 「{k}:」がありません")
        build_article(a, arts)
    for c in SITE["categories"]:
        build_category(c, arts)
    for p in pages:
        build_page(p)
    build_home(arts)
    build_404()
    build_feeds(arts, pages)
    print(f"記事 {len(arts)} 本、固定ページ {len(pages)} 本を作りました。")


