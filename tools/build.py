def write(path, text):
    full = os.path.join(ROOT, path.lstrip("/"), "index.html") if path.endswith("/") else os.path.join(ROOT, path.lstrip("/"))
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)
    return full


def clean_generated():
    """前回作ったページを消す(記事を消したり名前を変えたときに古いページが残らないように)"""
    emptied = set()
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if not x.startswith(".") and x not in ("content", "tools", "docs", "assets", "worker")]
        for fn in files:
            if fn.endswith(".html"):
                p = os.path.join(d, fn)
                with open(p, encoding="utf-8") as f:
                    if GENERATED_MARK in f.read(400):
                        os.remove(p)
                        emptied.add(d)
    for d in sorted(emptied, key=len, reverse=True):
        while d != ROOT and os.path.isdir(d) and not os.listdir(d):
            os.rmdir(d)
            d = os.path.dirname(d)


def build_article(a, arts):
    cat = CATS[a["cat"]]
    body, toc, faq = markdown(a["body"])
    bc_html, bc_ld = crumbs([(cat["name"], f'/{a["cat"]}/'), (a["title"], a["path"])])
    author = a.get("author", SITE["publisher"])
    article = {"@type": "Article", "headline": a["title"], "description": a.get("description", ""),
               "datePublished": a.get("date"), "dateModified": a.get("updated"),
               "mainEntityOfPage": BASE + a["path"], "inLanguage": "ja",
               "author": {"@type": "Person" if author != SITE["publisher"] else "Organization",
                          "name": author, "url": BASE + "/about/"},
               "publisher": ORG, "image": BASE + "/assets/og.png"}
    lds = [article, bc_ld]
    if faq:
        lds.append({"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": ans}} for q, ans in faq]})
    toc_html = ""
    h2s = [(hid, t, l) for lv, hid, t, l in toc if lv == 2]
    if len(h2s) >= 3:
        toc_html = '<nav class="toc" aria-label="目次"><p class="toc-h">目次</p><ol>' + "".join(
            f'<li><a href="#{hid}">{esc(t)}</a>' + (f' <span class="lv lv-{LEVELS[l][0]}">{l}</span>' if l else "") + "</li>"
            for hid, t, l in h2s) + "</ol></nav>"
    toc_html = level_guide(toc) + toc_html
    summary = (f'<div class="summary-box"><p class="summary-h">この記事の結論</p>'
               f'<p class="summary">{inline(a["summary"])}</p></div>') if a.get("summary") else ""
    related = [x for x in arts if x["cat"] == a["cat"] and x is not a][:6]
    rm_html = article_roadmap(a)
    rel_html = ('<section class="related"><h2 class="sec-h">あわせて読みたい</h2>' + cards(related) + "</section>") if related else ""
    upd = a.get("updated", "")
    page = head(a.get("seo_title", a["title"]), a.get("description", ""), a["path"], lds, "article") + f"""<div class="wrap narrow">
{bc_html}
<article class="post">
<header class="post-head c-{a['cat']}"><a class="chip" href="/{a['cat']}/">{esc(cat['name'])}</a>
<h1>{esc(a['title'])}</h1>
<p class="meta"><span>公開 <time datetime="{a.get('date', '')}">{a.get('date', '').replace("-", ".")}</time></span><span>更新 <time datetime="{upd}">{upd.replace("-", ".")}</time></span><span><a href="/about/">{esc(author)}</a></span></p>
</header>
{summary}
{toc_html}
<div class="body">
{body}
</div>
</article>
{rm_html}
{rel_html}
</div>
<script src="/assets/progress.js" defer></script>
""" + foot()
    write(a["path"], page)


def step_link(s):
    return f'<a href="/roadmap/#step-{s["id"]}">STEP {s["n"]}「{esc(s["title"])}」</a>'


def article_roadmap(a):
    """記事の末尾に「ロードマップのどこか・次にやること・自分のサイトで確かめる」を出す"""
    mine = [s for s in STEPS if a["path"] in s["articles"]]
    if not mine:
        return ""
    s = mine[0]
    nxt = STEPS[s["n"]] if s["n"] < len(STEPS) else None
    lis = [f'<li>この記事は、<a href="/roadmap/">AIO・SEO強化ロードマップ</a>の {step_link(s)} の解説です。'
           f'<label class="rm-check"><input type="checkbox" data-step="{s["id"]}"> このステップはできた</label></li>']
    lis += [f'<li>あわせて {step_link(x)} にも役立ちます。</li>' for x in mine[1:3]]
