esc = lambda s: html.escape(str(s), quote=True)


# ---------------------------------------------------------------- Markdown(必要な分だけ)
def inline(s):
    s = esc(s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)", r'<img src="\2" alt="\1" loading="lazy" decoding="async">', s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: link(m.group(1), m.group(2)), s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    return s


def link(text, href):
    ext = href.startswith("http") and not href.startswith(BASE)
    attrs = ' target="_blank" rel="noopener"' if ext else ""
    return f'<a href="{href}"{attrs}>{text}</a>'


def slugify_heading(text, used):
    base = re.sub(r"[^\w぀-ヿ一-鿿-]+", "-", text).strip("-").lower() or "h"
    s, i = base, 2
    while s in used:
        s, i = f"{base}-{i}", i + 1
    used.add(s)
    return s


# 見出しの末尾に [初級] [中級] [上級] と書くと、難易度のラベルとレベル別の読み方ガイドが付く
LEVELS = {"初級": ("basic", "はじめての方"), "中級": ("mid", "設定・実務をする方"), "上級": ("adv", "もっと深く知りたい方")}


def level_guide(toc):
    rows = []
    for name, (key, who) in LEVELS.items():
        hs = [(hid, t) for lv, hid, t, l in toc if lv == 2 and l == name]
        if hs:
            links = "、".join(f'<a href="#{hid}">{esc(t)}</a>' for hid, t in hs)
            rows.append(f'<li><span class="lv lv-{key}">{name}</span><strong>{who}</strong>:{links}</li>')
    if len(rows) < 2:
        return ""
    return '<nav class="guide" aria-label="レベル別の読み方"><p>レベル別の読み方</p><ul>' + "".join(rows) + "</ul></nav>"


def markdown(md):
    """Markdown を HTML にする。戻り値: (html, 見出しの一覧[(level, id, text)], FAQ[(q, a)])"""
    lines = md.replace("\r\n", "\n").split("\n")
    out, toc, faq, used = [], [], [], set()
    i, in_faq, cur_q, cur_a = 0, False, None, []

    def flush_q():
        nonlocal cur_q, cur_a
        if cur_q:
            faq.append((cur_q, re.sub(r"<[^>]+>", "", " ".join(cur_a)).strip()))
        cur_q, cur_a = None, []

    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.startswith("```"):
            buf = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            out.append("<pre><code>" + esc("\n".join(buf)) + "</code></pre>")
            continue
        m = re.match(r"(#{2,4})\s+(.*)", line)
        if m:
            level, text = len(m.group(1)), m.group(2).strip()
            lv = re.search(r"\s*\[(初級|中級|上級)\]$", text)
            badge = ""
            if lv:
                text = text[: lv.start()].strip()
                badge = f' <span class="lv lv-{LEVELS[lv.group(1)][0]}">{lv.group(1)}</span>'
            hid = slugify_heading(text, used)
            if level == 2:
                flush_q()
                in_faq = text in ("よくある質問", "FAQ")
            if level == 3 and in_faq:
                flush_q()
                cur_q = text
            if level <= 3:
                toc.append((level, hid, text, lv.group(1) if lv else ""))
            out.append(f'<h{level} id="{hid}">{inline(text)}{badge}</h{level}>')
            i += 1
            continue
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            t = ['<div class="table"><table>']
            for r, cells in enumerate(rows):
                tag = "th" if r == 0 else "td"
                t.append("<tr>" + "".join(f"<{tag}>{inline(c)}</{tag}>" for c in cells) + "</tr>")
            t.append("</table></div>")
            out.append("".join(t))
            continue
        if re.match(r"(\s*)([-*]|\d+\.)\s+", line):
            ordered = bool(re.match(r"\s*\d+\.", line))
            items = []
            while i < len(lines) and re.match(r"\s*([-*]|\d+\.)\s+", lines[i]):
                items.append(re.sub(r"^\s*([-*]|\d+\.)\s+", "", lines[i]))
                i += 1
            tag = "ol" if ordered else "ul"
            body = "".join(f"<li>{inline(x)}</li>" for x in items)
            out.append(f"<{tag}>{body}</{tag}>")
            if cur_q:
                cur_a.append(body)
            continue
        if line.startswith(">"):
            buf = []
            while i < len(lines) and lines[i].startswith(">"):
                buf.append(lines[i].lstrip("> ").rstrip())
                i += 1
            out.append("<blockquote><p>" + inline(" ".join(buf)) + "</p></blockquote>")
            continue
        buf = []
        while i < len(lines) and lines[i].strip() and not re.match(r"(#{2,4}\s|```|\||>|\s*([-*]|\d+\.)\s)", lines[i]):
            buf.append(lines[i].strip())
            i += 1
        p = inline("".join(buf))
        out.append(f"<p>{p}</p>")
        if cur_q:
            cur_a.append(p)
    flush_q()
    return "\n".join(out), toc, faq


# ---------------------------------------------------------------- 元データの読み込み
def read_md(path):
    text = open(path, encoding="utf-8").read()
    meta = {}
    if text.startswith("---"):
        head, text = text[3:].split("\n---", 1)
        for ln in head.strip().split("\n"):
            if ":" in ln:
                k, v = ln.split(":", 1)
                meta[k.strip()] = v.strip()
        text = text.lstrip("-\n")
    return meta, text


def load_articles():
    arts = []
    adir = os.path.join(ROOT, "content", "articles")
    for cat in sorted(os.listdir(adir)) if os.path.isdir(adir) else []:
        if cat.startswith("."):
            continue
        if cat not in CATS:
            sys.exit(f"不明なカテゴリ: content/articles/{cat}/ (site.json の categories に足してください)")
        for fn in sorted(os.listdir(os.path.join(adir, cat))):
            if not fn.endswith(".md"):
                continue
            meta, body = read_md(os.path.join(adir, cat, fn))
            if meta.get("draft") == "true":
                continue
            slug = fn[:-3]
            meta.setdefault("updated", meta.get("date", ""))
            arts.append({**meta, "cat": cat, "slug": slug, "body": body,
                         "path": f"/{cat}/{slug}/", "src": f"content/articles/{cat}/{fn}"})
    arts.sort(key=lambda a: a.get("date", ""), reverse=True)
    return arts


def load_pages():
    pages = []
    pdir = os.path.join(ROOT, "content", "pages")
    for fn in sorted(os.listdir(pdir)) if os.path.isdir(pdir) else []:
        if fn.endswith(".md"):
            meta, body = read_md(os.path.join(pdir, fn))
            pages.append({**meta, "slug": fn[:-3], "body": body, "path": f"/{fn[:-3]}/"})
    return pages


