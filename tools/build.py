def crumbs(items):
    """items: [(name, path)]。HTML と BreadcrumbList を返す"""
    allc = [("ホーム", "/")] + items
    h = '<nav class="crumbs" aria-label="パンくず"><ol>' + "".join(
        f'<li><a href="{p}">{esc(n)}</a></li>' if k < len(allc) - 1 else f'<li><span aria-current="page">{esc(n)}</span></li>'
        for k, (n, p) in enumerate(allc)) + "</ol></nav>"
    data = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": k + 1, "name": n, "item": BASE + p} for k, (n, p) in enumerate(allc)]}
    return h, data


def card(a, show_cat=True):
    chip = f'<span class="chip">{esc(short(a["cat"]))}</span>' if show_cat else ""
    return (f'<li class="card c-{a["cat"]}"><a href="{a["path"]}">{chip}'
            f'<strong class="card-t">{esc(a["title"])}</strong><span class="desc">{esc(a.get("description", ""))}</span>'
            f'<span class="card-f"><time datetime="{a.get("updated", "")}">{a.get("updated", "").replace("-", ".")}</time> 更新</span></a></li>')


def cards(items, cls="cards", show_cat=True):
    return f'<ul class="{cls}">' + "".join(card(a, show_cat) for a in items) + "</ul>"


def band(inner, cls=""):
    """ページ上部の帯(タイトル・説明)"""
    return f'<section class="band {cls}"><div class="wrap">{inner}</div></section>\n'


